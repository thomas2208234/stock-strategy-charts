"use client"

import { X } from "lucide-react"
import { useState } from "react"
import { NumberField, Section, SelectField, Switch } from "@/components/ui"
import type { AppSettings, ChartConfig, EntryRule, ExitRule, MaType } from "@/lib/settings"

const MA_TYPES: { value: MaType; label: string }[] = [
  { value: "EMA", label: "EMA" },
  { value: "SMA", label: "SMA" },
]

const ENTRY_RULES: { value: EntryRule; label: string }[] = [
  { value: "ma_cross", label: "Fast MA crosses above slow MA" },
  { value: "rsi_reversal", label: "RSI crosses up out of oversold" },
  { value: "macd_cross", label: "MACD crosses above signal" },
  { value: "vwap_reclaim", label: "Price closes back above VWAP" },
]

const EXIT_RULES: { value: ExitRule; label: string }[] = [
  { value: "opposite", label: "Opposite of entry signal" },
  { value: "rsi_overbought", label: "RSI reaches overbought" },
  { value: "macd_cross_down", label: "MACD crosses below signal" },
  { value: "vwap_lose", label: "Price closes below VWAP" },
  { value: "none", label: "Stop / target only" },
]

export function StrategyPanel({
  settings,
  update,
  activeChart,
  onChangeChart,
}: {
  settings: AppSettings
  update: (fn: (s: AppSettings) => AppSettings) => void
  activeChart: ChartConfig
  onChangeChart: (patch: Partial<ChartConfig>) => void
}) {
  const ind = settings.indicators
  const strat = settings.strategy
  const setInd = <K extends keyof AppSettings["indicators"]>(k: K, patch: Partial<AppSettings["indicators"][K]>) =>
    update((s) => ({ ...s, indicators: { ...s.indicators, [k]: { ...s.indicators[k], ...patch } } }))
  const setStrat = (patch: Partial<AppSettings["strategy"]>) => update((s) => ({ ...s, strategy: { ...s.strategy, ...patch } }))
  const setLevels = (patch: Partial<AppSettings["levels"]>) => update((s) => ({ ...s, levels: { ...s.levels, ...patch } }))
  const [levelInput, setLevelInput] = useState("")

  return (
    <div className="flex flex-col">
      <div className="border-b bg-warn/10 px-4 py-3">
        <p className="text-xs leading-relaxed text-warn">
          Educational use only. Signals are generated by simple rules on historical bars, ignore fees and slippage, and do not
          predict or guarantee future results. Nothing here is a claim that any strategy is profitable or is financial advice.
        </p>
      </div>

      <Section title="Moving averages">
        <Switch label="Fast MA" checked={ind.fastMa.enabled} onChange={(v) => setInd("fastMa", { enabled: v })} />
        <div className="grid grid-cols-2 gap-2">
          <SelectField label="Type" value={ind.fastMa.type} options={MA_TYPES} onChange={(v) => setInd("fastMa", { type: v })} />
          <NumberField label="Length" value={ind.fastMa.period} min={2} max={400} onChange={(v) => setInd("fastMa", { period: v })} />
        </div>
        <Switch label="Slow MA" checked={ind.slowMa.enabled} onChange={(v) => setInd("slowMa", { enabled: v })} />
        <div className="grid grid-cols-2 gap-2">
          <SelectField label="Type" value={ind.slowMa.type} options={MA_TYPES} onChange={(v) => setInd("slowMa", { type: v })} />
          <NumberField label="Length" value={ind.slowMa.period} min={2} max={400} onChange={(v) => setInd("slowMa", { period: v })} />
        </div>
      </Section>

      <Section title="VWAP">
        <Switch
          label="Show VWAP"
          description="Session-anchored; resets each day in the exchange time zone. Not meaningful on the daily timeframe."
          checked={ind.vwap.enabled}
          onChange={(v) => setInd("vwap", { enabled: v })}
        />
      </Section>

      <Section title="RSI">
        <Switch label="Show RSI pane" checked={ind.rsi.enabled} onChange={(v) => setInd("rsi", { enabled: v })} />
        <NumberField label="Length" value={ind.rsi.period} min={2} max={100} onChange={(v) => setInd("rsi", { period: v })} />
        <NumberField label="Overbought" value={ind.rsi.overbought} min={50} max={95} onChange={(v) => setInd("rsi", { overbought: v })} />
        <NumberField label="Oversold" value={ind.rsi.oversold} min={5} max={50} onChange={(v) => setInd("rsi", { oversold: v })} />
      </Section>

      <Section title="MACD">
        <Switch label="Show MACD pane" checked={ind.macd.enabled} onChange={(v) => setInd("macd", { enabled: v })} />
        <NumberField label="Fast" value={ind.macd.fast} min={2} max={100} onChange={(v) => setInd("macd", { fast: v })} />
        <NumberField label="Slow" value={ind.macd.slow} min={3} max={200} onChange={(v) => setInd("macd", { slow: v })} />
        <NumberField label="Signal" value={ind.macd.signal} min={2} max={50} onChange={(v) => setInd("macd", { signal: v })} />
      </Section>

      <Section title="Entry & exit signals">
        <Switch
          label="Show signal markers"
          description="Long-only. Evaluated on closed bars; the forming bar is ignored."
          checked={strat.enabled}
          onChange={(v) => setStrat({ enabled: v })}
        />
        <div className="flex flex-col gap-1.5">
          <SelectField label="Entry when" value={strat.entry} options={ENTRY_RULES} onChange={(v) => setStrat({ entry: v })} />
          <SelectField label="Exit when" value={strat.exit} options={EXIT_RULES} onChange={(v) => setStrat({ exit: v })} />
        </div>
        <Switch label="Only enter above VWAP" checked={strat.requireAboveVwap} onChange={(v) => setStrat({ requireAboveVwap: v })} />
        <Switch label="Only enter above slow MA" checked={strat.requireAboveSlowMa} onChange={(v) => setStrat({ requireAboveSlowMa: v })} />
      </Section>

      <Section title="Stop-loss & take-profit">
        <Switch label="Stop-loss" checked={strat.useStopLoss} onChange={(v) => setStrat({ useStopLoss: v })} />
        <NumberField label="Below entry" value={strat.stopLossPct} min={0.1} max={50} step={0.1} suffix="%" onChange={(v) => setStrat({ stopLossPct: v })} />
        <Switch label="Take-profit" checked={strat.useTakeProfit} onChange={(v) => setStrat({ useTakeProfit: v })} />
        <NumberField label="Above entry" value={strat.takeProfitPct} min={0.1} max={100} step={0.1} suffix="%" onChange={(v) => setStrat({ takeProfitPct: v })} />
      </Section>

      <Section title="Support & resistance">
        <Switch
          label="Auto levels from swing pivots"
          checked={settings.levels.autoEnabled}
          onChange={(v) => setLevels({ autoEnabled: v })}
        />
        <NumberField label="Pivot strength (bars)" value={settings.levels.strength} min={2} max={20} onChange={(v) => setLevels({ strength: v })} />
        <NumberField label="Levels per side" value={settings.levels.count} min={1} max={5} onChange={(v) => setLevels({ count: v })} />

        <form
          className="flex flex-col gap-2"
          onSubmit={(e) => {
            e.preventDefault()
            const n = Number(levelInput)
            if (Number.isFinite(n) && n > 0 && activeChart.levels.length < 10) {
              onChangeChart({ levels: [...activeChart.levels, n] })
              setLevelInput("")
            }
          }}
        >
          <label htmlFor="manual-level" className="text-sm text-muted-foreground">
            Manual level for <span className="font-mono text-foreground">{activeChart.symbol}</span> (selected chart)
          </label>
          <div className="flex gap-2">
            <input
              id="manual-level"
              type="number"
              inputMode="decimal"
              step="any"
              min={0}
              value={levelInput}
              onChange={(e) => setLevelInput(e.target.value)}
              placeholder="Price"
              className="h-8 min-w-0 flex-1 rounded-md border bg-background px-2 font-mono text-sm focus-visible:outline-2 focus-visible:outline-primary"
            />
            <button type="submit" className="h-8 rounded-md bg-primary px-3 text-xs font-medium text-primary-foreground">
              Add
            </button>
          </div>
        </form>
        {activeChart.levels.length > 0 && (
          <ul className="flex flex-wrap gap-1.5">
            {activeChart.levels.map((l, i) => (
              <li key={`${l}-${i}`} className="flex items-center gap-1 rounded border px-1.5 py-0.5 font-mono text-xs">
                {l}
                <button
                  type="button"
                  onClick={() => onChangeChart({ levels: activeChart.levels.filter((_, j) => j !== i) })}
                  aria-label={`Remove level ${l}`}
                  className="text-muted-foreground hover:text-foreground"
                >
                  <X className="size-3" />
                </button>
              </li>
            ))}
          </ul>
        )}
      </Section>
    </div>
  )
}
